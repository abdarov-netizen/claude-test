def sheet(wb,title,head,rows,widths,freeze='A2',wrapcols=()):
    ws=wb.create_sheet(title)
    ws.append(head)
    for c in range(1,len(head)+1):
        cell=ws.cell(1,c); cell.font=H; cell.fill=HF; cell.alignment=Alignment(wrap_text=True,vertical='center')
    for r in rows: ws.append(r)
    for i,w in enumerate(widths,1): ws.column_dimensions[get_column_letter(i)].width=w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment=WRAP if c.column in wrapcols else TOP
            c.border=THIN
    ws.freeze_panes=freeze; ws.auto_filter.ref=ws.dimensions
    return ws

